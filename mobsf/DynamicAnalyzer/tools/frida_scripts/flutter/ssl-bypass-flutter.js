var LIB = 'libflutter.so';
var ARCH_KEY = {arm64: 'arm64', arm: 'arm', ia32: 'x86', x64: 'x86_64'};
var patched = false;

function readBuildId(base) {
    // Parse the ELF program headers for the NT_GNU_BUILD_ID note.
    var phoff = base.add(0x20).readU64();
    var phentsize = base.add(0x36).readU16();
    var phnum = base.add(0x38).readU16();
    for (var i = 0; i < phnum; i++) {
        var ph = base.add(phoff.add(i * phentsize));
        if (ph.readU32() !== 4) continue; // PT_NOTE
        var p = base.add(ph.add(0x10).readU64()); // p_vaddr
        var end = p.add(ph.add(0x20).readU64());  // p_filesz
        while (p.compare(end) < 0) {
            var namesz = p.readU32();
            var descsz = p.add(4).readU32();
            var ntype = p.add(8).readU32();
            var namep = p.add(12);
            var descp = namep.add((namesz + 3) & ~3);
            if (ntype === 3 && namesz >= 3 && namep.readCString() === 'GNU') {
                var bytes = new Uint8Array(descp.readByteArray(descsz));
                return Array.prototype.map.call(
                    bytes, function (b) {
                        return ('0' + b.toString(16)).slice(-2);
                    }).join('');
            }
            p = descp.add((descsz + 3) & ~3);
        }
    }
    return null;
}

function neutralise(address, how) {
    if (patched) return;
    patched = true;
    try {
        Interceptor.replace(address, new NativeCallback(function () {
            return 0;
        }, 'int', ['pointer', 'int']));
        console.log('[flutter-ssl] ssl_verify_peer_cert neutralised (' +
                    how + ') at ' + address);
    } catch (e) {
        patched = false;
        console.log('[flutter-ssl] replace failed: ' + e);
    }
}

// Byte-pattern fallback, used when the build-id is not in the table.
var ARM64_PATTERNS = [
    'F? 0F 1C F8 F? 5? 01 A9 F? 5? 02 A9 F? ?? 03 A9 ?? ?? ?? ?? 68 1A 40 F9',
    'F? 43 01 D1 FE 67 01 A9 F8 5F 02 A9 F6 57 03 A9 F4 4F 04 A9 13 00 40 F9 F4 03 00 AA 68 1A 40 F9',
    'FF 43 01 D1 FE 67 01 A9 ?? ?? 06 94 ?? 7? 06 94 68 1A 40 F9 15 15 41 F9 B5 00 00 B4 B6 4A 40 F9'];
var ARM_PATTERNS = [
    '2D E9 F? 4? D0 F8 00 80 81 46 D8 F8 18 00 D0 F8 ??'];

function patternScan(mod) {
    var patterns = Process.arch === 'arm' ? ARM_PATTERNS : ARM64_PATTERNS;
    mod.enumerateRanges('r-x').forEach(function (range) {
        patterns.forEach(function (pattern) {
            if (patched) return;
            Memory.scan(range.base, range.size, pattern, {
                onMatch: function (address) {
                    neutralise(address, 'pattern');
                },
            });
        });
    });
}

function hook() {
    var mod = Process.findModuleByName(LIB);
    if (!mod) return;
    var buildId = null;
    try {
        buildId = readBuildId(mod.base);
    } catch (e) {
        console.log('[flutter-ssl] build-id read failed: ' + e);
    }
    var entry = buildId && FLUTTER_SSL_OFFSETS[buildId];
    var offset = entry && entry[ARCH_KEY[Process.arch] || Process.arch];
    if (offset) {
        neutralise(mod.base.add(offset), 'build-id ' + buildId);
        return;
    }
    if (buildId) {
        console.log('[flutter-ssl] build-id ' + buildId + ' (' +
                    Process.arch + ') not in table; scanning. ' +
                    'Regenerate the offsets table to cover this engine.');
    }
    patternScan(mod);
}

if (Process.findModuleByName(LIB)) {
    hook();
} else {
    // libflutter.so is loaded after start-up; hook once its ctors run.
    var linker = Process.arch === 'arm' ? 'linker' : 'linker64';
    var doDlopen = null;
    var callCtor = null;
    var mod = Process.findModuleByName(linker);
    if (mod) {
        mod.enumerateSymbols().forEach(function (sym) {
            if (sym.name.indexOf('do_dlopen') !== -1) doDlopen = sym.address;
            else if (sym.name.indexOf('call_constructor') !== -1) {
                callCtor = sym.address;
            }
        });
    }
    if (doDlopen && callCtor) {
        var reg = Process.arch === 'arm' ? 'r0' : 'x0';
        Interceptor.attach(doDlopen, function () {
            var path = this.context[reg].readCString();
            if (path && path.indexOf(LIB) !== -1) {
                Interceptor.attach(callCtor, function () {
                    hook();
                });
            }
        });
    } else {
        console.log('[flutter-ssl] linker symbols not found');
    }
}
