// Flutter TLS verification bypass (F22).
//
// Flutter's HTTP stack uses its own BoringSSL inside libflutter.so and
// ignores the system proxy and user CA store, so a MITM proxy cannot read
// its HTTPS traffic. This neutralises the engine's certificate check by
// replacing bssl::ssl_verify_peer_cert with a function that returns 0 (ok).
//
// The function has no exported symbol and moves with every engine build.
// The engine is identified by its GNU build-id (read from the loaded ELF)
// and the offset is looked up in the table below. If the build-id is not
// in the table, a byte-pattern scan is used as a fallback (arm64 and arm).
//
// Regenerate the table with scripts/update_flutter_frida_offsets.py.

