# -*- coding: utf_8 -*-
"""Identify the Flutter version from the Flutter engine revision.

flutter_engines.json maps engine revisions (bin/internal/engine.version at
each stable Flutter tag) to Flutter versions; it is generated by
scripts/update_flutter_dart_versions.py.

Android: libflutter.so embeds its engine revision as a 40-character hex
string, next to a few other revisions, so every standalone 40-hex string
is looked up and only a known engine revision matches.
iOS: the binary does not embed it; Flutter.framework/Info.plist has
FlutterEngine (revision) and BuildMode.
"""
import json
import logging
import plistlib
import re
from functools import lru_cache
from pathlib import Path, PurePosixPath

from mobsf.MobSF.security import (
    is_path_traversal,
    is_safe_path,
)
from mobsf.StaticAnalyzer.views.flutter.fileio import open_regular

logger = logging.getLogger(__name__)

DATA_FILE = Path(__file__).resolve().parent / 'flutter_engines.json'
REV_RE = re.compile(rb'(?<![0-9A-Za-z])[0-9a-f]{40}(?![0-9A-Za-z])')
MAX_SIZE = 512 * 1024 * 1024
CHUNK_SIZE = 4 * 1024 * 1024
TAIL = 41
PLIST_MAX_SIZE = 256 * 1024
PLIST_REV_RE = re.compile(r'^[0-9a-f]{40}$')
BUILD_MODES = ('debug', 'profile', 'release')


@lru_cache(maxsize=1)
def load_flutter_engines():
    """Load the engine revision table."""
    with DATA_FILE.open(encoding='utf-8') as fobj:
        return json.load(fobj)


def engine_revisions(path, max_size=MAX_SIZE, chunk_size=CHUNK_SIZE):
    """Return the set of standalone 40-hex strings in a file."""
    revs = set()
    try:
        fobj = open_regular(path, max_size)
        if fobj is None:
            return revs
        with fobj:
            buf = b''
            carried = False
            while True:
                chunk = fobj.read(chunk_size)
                eof = not chunk
                buf += chunk
                for match in REV_RE.finditer(buf):
                    # The run may continue in the next chunk
                    if match.end() == len(buf) and not eof:
                        continue
                    # Judged with its preceding byte in the last chunk
                    if carried and match.start() == 0:
                        continue
                    revs.add(match.group().decode('ascii'))
                if eof:
                    return revs
                buf = buf[-TAIL:]
                carried = True
    except FileNotFoundError:
        pass
    except Exception:
        logger.exception('Failed to read Flutter engine revision')
    return revs


def flutter_from_engine(path):
    """Return {'engine', 'flutter'} for a libflutter.so, else None."""
    table = load_flutter_engines()
    for rev in sorted(engine_revisions(path)):
        if rev in table:
            return {'engine': rev, 'flutter': table[rev]}
    return None


def flutter_from_framework_plist(path, max_size=PLIST_MAX_SIZE):
    """Return {'engine', 'flutter', 'build_mode'} from Flutter.framework.

    Returns None if the Info.plist cannot be read or parsed.
    """
    try:
        fobj = open_regular(path, max_size)
        if fobj is None:
            return None
        with fobj:
            # plistlib rejects XML entity declarations
            data = plistlib.loads(fobj.read(max_size + 1))
    except FileNotFoundError:
        return None
    except Exception:
        logger.warning('Failed to parse Flutter.framework Info.plist')
        return None
    if not isinstance(data, dict):
        return None
    rev = data.get('FlutterEngine')
    rev = rev if isinstance(rev, str) and PLIST_REV_RE.match(rev) else None
    mode = data.get('BuildMode')
    mode = mode if mode in BUILD_MODES else None
    return {
        'engine': rev,
        'flutter': load_flutter_engines().get(rev, []) if rev else [],
        'build_mode': mode,
    }


def flutter_engine_info(app_dir, engine_rel):
    """Engine revision and Flutter version for an engine path from detect.

    engine_rel is relative to app_dir: lib/<abi>/libflutter.so (Android)
    or .../Flutter.framework/Flutter (iOS).
    """
    if not engine_rel or is_path_traversal(engine_rel):
        return None
    rel = PurePosixPath(engine_rel.replace('\\', '/'))
    if rel.name == 'libflutter.so':
        target = rel
    elif rel.name == 'Flutter' and rel.parent.name == 'Flutter.framework':
        target = rel.parent / 'Info.plist'
    else:
        return None
    full = Path(app_dir) / target
    if not is_safe_path(app_dir, full, target.as_posix()):
        return None
    if target.name == 'libflutter.so':
        return flutter_from_engine(full)
    return flutter_from_framework_plist(full)
