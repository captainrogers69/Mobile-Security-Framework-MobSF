# -*- coding: utf_8 -*-
"""Identify the Flutter version from the engine revision in libflutter.so.

flutter_engines.json maps engine revisions (bin/internal/engine.version at
each stable Flutter tag) to Flutter versions; it is generated by
scripts/update_flutter_dart_versions.py. libflutter.so embeds its engine
revision as a 40-character hex string, next to a few other revisions, so
every standalone 40-hex string is looked up and only a known engine
revision matches.
"""
import json
import logging
import re
from functools import lru_cache
from pathlib import Path

from mobsf.StaticAnalyzer.views.flutter.fileio import open_regular

logger = logging.getLogger(__name__)

DATA_FILE = Path(__file__).resolve().parent / 'flutter_engines.json'
REV_RE = re.compile(rb'(?<![0-9A-Za-z])[0-9a-f]{40}(?![0-9A-Za-z])')
MAX_SIZE = 512 * 1024 * 1024
CHUNK_SIZE = 4 * 1024 * 1024
TAIL = 41


@lru_cache(maxsize=1)
def load_flutter_engines():
    """Load the engine revision table."""
    with DATA_FILE.open(encoding='utf-8') as fobj:
        return json.load(fobj)


def engine_revisions(path, max_size=MAX_SIZE, chunk_size=CHUNK_SIZE):
    """Return the set of standalone 40-hex strings in a file."""
    revs = set()
    try:
        fobj = open_regular(path, max_size)
        if fobj is None:
            return revs
        with fobj:
            buf = b''
            carried = False
            while True:
                chunk = fobj.read(chunk_size)
                eof = not chunk
                buf += chunk
                for match in REV_RE.finditer(buf):
                    # The run may continue in the next chunk
                    if match.end() == len(buf) and not eof:
                        continue
                    # Judged with its preceding byte in the last chunk
                    if carried and match.start() == 0:
                        continue
                    revs.add(match.group().decode('ascii'))
                if eof:
                    return revs
                buf = buf[-TAIL:]
                carried = True
    except FileNotFoundError:
        pass
    except Exception:
        logger.exception('Failed to read Flutter engine revision')
    return revs


def flutter_from_engine(path):
    """Return {'engine', 'flutter'} for a libflutter.so, else None."""
    table = load_flutter_engines()
    for rev in sorted(engine_revisions(path)):
        if rev in table:
            return {'engine': rev, 'flutter': table[rev]}
    return None
