# -*- coding: utf_8 -*-
"""Map a Dart snapshot hash to Dart SDK and Flutter versions.

dart_versions.json was generated by compiling an AOT snapshot with every
stable Dart SDK from the official archive (macOS arm64, Dart >= 2.14)
and reading its header, then joining with Flutter's official
releases_macos.json (dart_sdk_version) for the Flutter versions.
flutter_dart.json maps each Flutter version to the Dart version it ships.
"""
import json
import re
from functools import lru_cache
from pathlib import Path

HASH_RE = re.compile(r'^[0-9a-f]{32}$')
DATA_FILE = Path(__file__).resolve().parent / 'dart_versions.json'
FLUTTER_DART_FILE = Path(__file__).resolve().parent / 'flutter_dart.json'


@lru_cache(maxsize=1)
def load_dart_versions():
    """Load the snapshot hash table."""
    with DATA_FILE.open(encoding='utf-8') as fobj:
        return json.load(fobj)


@lru_cache(maxsize=1)
def load_flutter_dart():
    """Load the Flutter version -> Dart version table."""
    with FLUTTER_DART_FILE.open(encoding='utf-8') as fobj:
        return json.load(fobj)


def dart_for_flutter(flutter_versions):
    """Dart versions shipped by the given Flutter versions."""
    table = load_flutter_dart()
    return sorted(
        {table[v] for v in flutter_versions or [] if v in table},
        key=lambda v: tuple(int(x) for x in v.split('.')))


def narrow_dart(dart, flutter):
    """Narrow snapshot Dart versions with the Flutter version(s).

    A snapshot hash covers several Dart releases; the engine names the
    exact Flutter release, which ships one Dart release. If the two
    sources disagree, the snapshot list is kept.
    """
    shipped = dart_for_flutter(flutter)
    if not dart:
        return shipped
    common = [v for v in dart if v in shipped]
    return common or list(dart)


def dart_version(snap_hash):
    """Return {'dart': [...], 'flutter': [...]} for a hash, else None."""
    if not isinstance(snap_hash, str) or not HASH_RE.match(snap_hash):
        return None
    return load_dart_versions().get(snap_hash)
