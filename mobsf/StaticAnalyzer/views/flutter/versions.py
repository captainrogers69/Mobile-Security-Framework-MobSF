# -*- coding: utf_8 -*-
"""Map a Dart snapshot hash to Dart SDK and Flutter versions.

dart_versions.json was generated by compiling an AOT snapshot with every
stable Dart SDK from the official archive (macOS arm64, Dart >= 2.14)
and reading its header, then joining with Flutter's official
releases_macos.json (dart_sdk_version) for the Flutter versions.
"""
import json
import re
from functools import lru_cache
from pathlib import Path

HASH_RE = re.compile(r'^[0-9a-f]{32}$')
DATA_FILE = Path(__file__).resolve().parent / 'dart_versions.json'


@lru_cache(maxsize=1)
def load_dart_versions():
    """Load the snapshot hash table."""
    with DATA_FILE.open(encoding='utf-8') as fobj:
        return json.load(fobj)


def dart_version(snap_hash):
    """Return {'dart': [...], 'flutter': [...]} for a hash, else None."""
    if not isinstance(snap_hash, str) or not HASH_RE.match(snap_hash):
        return None
    return load_dart_versions().get(snap_hash)
